import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { generateTypes } from "prismic-ts-codegen";

const root = process.cwd();
const config = JSON.parse(readFileSync(join(root, "slicemachine.config.json"), "utf8"));
const library = (config.libraries?.[0] ?? "./src/lib/slices").replace(/^\.\//, "");

const customTypeModels = readdirSync(join(root, "customtypes"))
  .filter((dir) => existsSync(join(root, "customtypes", dir, "index.json")))
  .sort()
  .map((dir) => JSON.parse(readFileSync(join(root, "customtypes", dir, "index.json"), "utf8")));

const sliceDirs = readdirSync(join(root, library), { withFileTypes: true })
  .filter(
    (entry) => entry.isDirectory() && existsSync(join(root, library, entry.name, "model.json")),
  )
  .map((entry) => entry.name)
  .sort();

const sharedSliceModels = sliceDirs.map((dir) =>
  JSON.parse(readFileSync(join(root, library, dir, "model.json"), "utf8")),
);

const types = generateTypes({
  customTypeModels,
  sharedSliceModels,
  clientIntegration: { includeContentNamespace: true, includeCreateClientInterface: true },
  typesProvider: "@prismicio/client",
});
writeFileSync(
  join(root, "src/prismicio-types.d.ts"),
  `// Code generated by Slice Machine. DO NOT EDIT.\n\n${types}`,
);

const imports = sliceDirs.map((dir) => `import ${dir} from "./${dir}/index.svelte";`).join("\n");
const entries = sliceDirs
  .map((dir, i) => `  ${sharedSliceModels[i].id}: ${dir},`)
  .sort()
  .join("\n");
writeFileSync(
  join(root, library, "index.js"),
  `// Code generated by Slice Machine. DO NOT EDIT.\n\n${imports}\n\nexport const components = {\n${entries}\n};\n`,
);

console.log(`${customTypeModels.length} custom types, ${sliceDirs.length} slices`);
